#!/bin/bash

# Выходим при ошибках
set -euo pipefail

LOG_FILE="access.log"

# Проверяем, передал ли пользователь IP-адрес
if [ -z "${1:-}" ]; then
    echo "Использование: $0 <IP_адрес>"
    echo "Пример: $0 10.0.0.5"
    exit 1
fi

IP="$1"

# Проверяем, существует ли файл лога
if [ ! -f "$LOG_FILE" ]; then
    echo "Ошибка: файл $LOG_FILE не найден в текущей директории!"
    exit 1
fi

echo "==========================================="
echo "Анализ активности IP-адреса: $IP"
echo "==========================================="

echo -e "\n[+] Запросы (URL и код ответа):"
# Ищем строки с нужным IP, выводим 7-ю (URL) и 9-ю (код) колонки
grep "^$IP" "$LOG_FILE" | awk '{print $7, $9}' || echo "Запросов с этого IP не найдено."

echo -e "\n[+] Количество ошибок (4xx и 5xx):"
# Ищем строки с IP, берем код ответа, фильтруем 4xx/5xx и считаем
grep "^$IP" "$LOG_FILE" | awk '{print $9}' | grep -E '^[45][0-9]{2}$' | sort | uniq -c || echo "Ошибок не найдено."

echo -e "\n==========================================="
